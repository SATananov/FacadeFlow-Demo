import { useState } from 'react'

export type AiWorkflowCoachMode = 'QUICK' | 'AI_TEXT'

interface Props {
  mode: AiWorkflowCoachMode
  selectionApplied: boolean
  hasQuickIntent: boolean
  exactProfileCodesComplete: boolean
}

function coachCopy({ mode, selectionApplied, hasQuickIntent, exactProfileCodesComplete }: Omit<Props, never>) {
  if (!selectionApplied && mode === 'QUICK') {
    return {
      step: 'СТЪПКА 1 · СЪЗДАЙ ИЗДЕЛИЕТО',
      title: 'Не знаеш откъде да започнеш? Следвай тези 4 действия.',
      body: 'За стандартен прозорец или врата не е нужно да пишеш техническо описание. Избери готовите стойности една по една.',
      items: [
        '1. Избери изделие, размер и количество.',
        '2. Избери най-близката визуална схема.',
        '3. Ако знаеш система и точни профилни кодове — отвори „Технически настройки“. Ако не ги знаеш, остави ги Неуточнено.',
        '4. Натисни „Използвай този избор“ и после провери AI скицата.',
      ],
      note: 'Важно: ако не знаеш нещо, не гадай. FacadeFlow трябва да го остави НЕУТОЧНЕНО, а не да измисля стойност.',
    }
  }

  if (!selectionApplied && mode === 'AI_TEXT') {
    return {
      step: 'СТЪПКА 1 · ОПИШИ С ДУМИ',
      title: 'Можеш да пишеш нормално, без специален технически формат.',
      body: 'Кажи какво искаш да се получи. FacadeFlow ще разчете само това, което действително си написал, и ще остави липсващото за проверка.',
      items: [
        '1. Кажи какво е изделието и размерите.',
        '2. Кажи кои полета са фиксирани или отваряеми.',
        '3. Ако знаеш система, профили, стъклопакет или обков — добави ги. Ако не ги знаеш, пропусни ги.',
        '4. Прегледай разчетеното и коригирай само това, което не е правилно.',
      ],
      note: 'Пример: „Прозорец 1200 × 1400, три полета, средното осово-откидно дясно, другите две фиксирани.“',
    }
  }

  if (hasQuickIntent && exactProfileCodesComplete) {
    return {
      step: 'СТЪПКА 2 · ПРОВЕРИ СКИЦАТА И ПРОФИЛИТЕ',
      title: 'Изборът е структуриран. Сега само проверяваш дали FacadeFlow е разбрал правилно.',
      body: 'Гледай първо общата скица. Под нея са реалните каталогови сечения за изрично избраните профили.',
      items: [
        '1. Провери размерите, броя полета и посоката на отваряне.',
        '2. A-A е касата, B-B е делителят, C-C е крилото.',
        '3. Натисни „Разгледай подробно“ само ако искаш по-голямо сечение и измервателните данни.',
        '4. След това премини към човешкия преглед. Нищо не се приема автоматично.',
      ],
      note: 'Каталоговите форми са източникът на визуална истина. Human-confirmed размерните правила се показват отделно.',
    }
  }

  if (hasQuickIntent) {
    return {
      step: 'СТЪПКА 2 · ПРОВЕРИ СКИЦАТА',
      title: 'Основната схема е готова, но няма избрани всички точни профилни кодове.',
      body: 'Това не е грешка. FacadeFlow не трябва да избира профили вместо теб.',
      items: [
        '1. Провери размера, полетата и отваряемостта.',
        '2. Ако знаеш точните кодове, избери „Нов бърз избор“ и отвори „Технически настройки“.',
        '3. Ако не знаеш точния код, остави го Неуточнено.',
        '4. Профилно сечение се показва само когато кодът е изрично зададен и има проверена каталогова визуализация.',
      ],
      note: 'Правило: по-добре НЕУТОЧНЕНО, отколкото измислен профил.',
    }
  }

  return {
    step: 'СТЪПКА 2 · ПРОВЕРИ РАЗЧЕТА',
    title: 'Прегледай какво е разпознато и какво още липсва.',
    body: 'AI описанието е само предложение за човешка проверка. Липсващите стойности трябва да останат видими като неуточнени.',
    items: [
      '1. Провери общия размер и типа изделие.',
      '2. Провери полетата и отваряемостта.',
      '3. Провери системата и профилните кодове само ако са изрично зададени.',
      '4. Поправи неясното и продължи към Human Review.',
    ],
    note: 'Не е нужно да разбираш всеки технически термин предварително — помощните описания трябва да ти казват какво означава следващата стъпка.',
  }
}

export function AiWorkflowCoach(props: Props) {
  const [open, setOpen] = useState(true)
  const copy = coachCopy(props)

  return <section className={`ff-ai-workflow-coach ${open ? 'is-open' : 'is-collapsed'}`} aria-label="Помощник за следващата стъпка">
    <button type="button" className="ff-ai-workflow-coach-toggle" onClick={() => setOpen((value) => !value)} aria-expanded={open}>
      <span><b>🧭 НЕ ЗНАЕШ КАКВО ДА ПРАВИШ?</b><strong>Помощник · Какво да направя сега?</strong></span>
      <em>{open ? 'Свий помощта' : 'Покажи помощта'}</em>
    </button>
    {open && <div className="ff-ai-workflow-coach-body">
      <div className="ff-ai-workflow-coach-copy"><span>{copy.step}</span><h3>{copy.title}</h3><p>{copy.body}</p></div>
      <ol>{copy.items.map((item) => <li key={item}>{item}</li>)}</ol>
      <div className="ff-ai-workflow-coach-note"><b>Ако се колебаеш:</b><span>{copy.note}</span></div>
    </div>}
  </section>
}
